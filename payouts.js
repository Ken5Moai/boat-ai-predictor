  const D=module.exports;
  const all=[];
  for(const v of D) for(const [rno,pay,pop] of v.rows) all.push({venue:v.venue,rno,pay,pop});
  const ok=all.filter(x=>x.pop!=null);
  console.log(`\n${D.length}場 ${all.length}レース（返還で人気が出ないもの ${all.length-ok.length}件を除く → ${ok.length}件）`);

